"""Read access to the vendored operation index (``index.json``).

The index is generated by ``tools/build.py`` from the TOTVS TTALK specs and
carries provenance (repository, commit, date). It is the same data the
generated facade was built from, so it can drive catalogs, tool descriptions
or documentation without importing the API modules.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from functools import lru_cache
from importlib import resources
from typing import Any


@lru_cache(maxsize=1)
def load_index() -> dict[str, Any]:
    with resources.files(__package__).joinpath("index.json").open("r", encoding="utf-8") as fh:
        return json.load(fh)


def provenance() -> dict[str, Any]:
    return dict(load_index()["provenance"])


def apis() -> list[dict[str, Any]]:
    return list(load_index()["apis"])


def get_api(api_id: str) -> dict[str, Any]:
    for api in load_index()["apis"]:
        if api["id"] == api_id:
            return api
    raise KeyError(api_id)


def iter_operations(*, side_effect: bool | None = None) -> Iterator[dict[str, Any]]:
    """Yield operation records (with ``api_id`` and ``base_path`` attached)."""
    for api in load_index()["apis"]:
        for op in api["operations"]:
            if side_effect is not None and op["side_effect"] != side_effect:
                continue
            yield {**op, "api_id": api["id"], "base_path": api["base_path"]}


def get_operation(operation_id: str) -> dict[str, Any]:
    """Look up by index id (``customer_vendor_v1.list_customer_vendor``)."""
    for op in iter_operations():
        if op["id"] == operation_id:
            return op
    raise KeyError(operation_id)
